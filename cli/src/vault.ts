// `saw vault sync`: indexes this project in the central personal Obsidian
// vault (knowledge.vault_path). It writes one note per project, and with
// knowledge.store = vault | both also copies docs/learnings/ there so
// learnings can be found across projects. The vault is outside the repo, so
// vault_path is only honoured from the global or local layer, never from a
// committed workflow.toml.

import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, isAbsolute, join } from "node:path";
import type { Layer } from "./config";
import type { TaskMetric } from "./metrics";

export interface VaultResult {
  note: string;
  copied: string[];
  warnings: string[];
}

const mdFiles = (dir: string): string[] => (existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".md") && f !== "README.md").sort() : []);
const slug = (s: string): string => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "project";

// Returns the vault path, or an error message.
export function vaultPath(path: string, source: Layer | undefined): { path?: string; error?: string } {
  if (!path) return { error: "knowledge.vault_path is not set; set it with saw config set knowledge.vault_path <dir> --scope global" };
  if (source === "project") return { error: "knowledge.vault_path is a personal path: set it in ~/.saw/config.toml or workflow.local.toml, not workflow.toml" };
  if (!isAbsolute(path)) return { error: "knowledge.vault_path must be an absolute path" };
  if (!existsSync(path)) return { error: `vault not found: ${path}` };
  return { path };
}

export function projectNote(name: string, cwd: string, metrics: TaskMetric[], today: string, linked = true): string {
  const docs = join(cwd, "docs");
  const list = (sub: string): string[] => mdFiles(join(docs, sub)).map((f) => `- ${f.replace(/\.md$/, "")}`);
  const verified = metrics.filter((m) => m.label === "Verified").length;
  const section = (title: string, items: string[]): string => `## ${title}\n${items.length ? items.join("\n") : "- none yet"}\n`;
  return `---
project: ${name}
path: "${cwd.replaceAll("\\", "/")}"
updated: ${today}
tags: [project]
---
# ${name}

${metrics.length} tasks, ${metrics.length ? Math.round((verified / metrics.length) * 100) : 0}% Verified. Source of truth is the project's own \`docs/\`; this note is regenerated by \`saw vault sync\`.

${section("Decisions", list("decisions"))}
${section("Features", list("features"))}
${section("Learnings", linked ? list("learnings").map((l) => `${l} → [[learnings/${slug(name)}/${l.slice(2)}]]`) : list("learnings"))}`;
}

export function syncVault(vault: string, cwd: string, store: string, metrics: TaskMetric[], dryRun = false, today = new Date().toISOString().slice(0, 10)): VaultResult {
  const name = basename(cwd);
  const result: VaultResult = { note: join(vault, "projects", `${slug(name)}.md`), copied: [], warnings: [] };
  // Two projects with the same folder name share a slug: don't let one silently replace the other.
  const prior = existsSync(result.note) ? /^path: "(.*)"$/m.exec(readFileSync(result.note, "utf8"))?.[1] : undefined;
  if (prior !== undefined && prior !== cwd.replaceAll("\\", "/")) {
    result.warnings.push(`${result.note} belongs to ${prior}; rename this folder or remove that note`);
    return result;
  }
  const learnings = join(cwd, "docs", "learnings");
  const dest = join(vault, "learnings", slug(name));
  if (store === "vault" || store === "both") {
    for (const f of mdFiles(learnings)) {
      const target = join(dest, f);
      if (existsSync(target) && readFileSync(target, "utf8") !== readFileSync(join(learnings, f), "utf8")) {
        // Edited in the vault since the last sync: the repo copy wins, but say so.
        result.warnings.push(`learnings/${slug(name)}/${f} was changed in the vault; overwritten by the repo copy`);
      }
      result.copied.push(f);
      if (!dryRun) {
        mkdirSync(dest, { recursive: true });
        copyFileSync(join(learnings, f), target);
      }
    }
  }
  if (store === "both") result.warnings.push("knowledge.store = both keeps two copies; edit learnings in the repo only");
  if (!dryRun) {
    mkdirSync(join(vault, "projects"), { recursive: true });
    writeFileSync(result.note, projectNote(name, cwd, metrics, today, store !== "repo"));
  }
  return result;
}
